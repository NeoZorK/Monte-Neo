"""Verified results for the catalog, read from Strategy Lab data (never typed by hand).

Sources: ``strategy_lab/results/summary.json`` (crypto track) and ``etf_summary.json`` (ETF track). The mapping from a
catalog id to a result is the explicit file ``lab_map.json``. Used by ``build_catalog.py``.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LAB = ROOT.parents[1] / "strategy_lab" / "results"
NOTE = "validation only, holdout sealed, provisional rules, not investment advice"
NOT_VERIFIED = "not yet verified"


def _f(v, nd=2):
    return "n/a" if v is None else f"{v:.{nd}f}"


def lab_rows() -> list[dict]:
    """Every Strategy Lab result as one flat dict (crypto and ETF tracks)."""
    rows = []
    summary = json.loads((LAB / "summary.json").read_text(encoding="utf-8"))
    for s in summary["strategies"]:
        rows.append({"kind": "lab", "name": s["name"], "title": s["title"], "family": s["family"], "verdict": s["verdict"], "arl": s["arl"], "depth": s["arl_depth"],
                     "net_sharpe": s.get("net_sharpe_val"), "sharpe_x2": s.get("net_sharpe_val_cost_x2"), "dsr": s["deflated_sharpe"], "n_trials": s["n_trials"],
                     "alpha_t": s.get("alpha_t_vs_btc"), "beta_share": s.get("beta_share"), "period": f"validation slice '{s['data_slice']}'", "date": s["date"][:10],
                     "certificate_id": s["certificate_id"]})
    for e in json.loads((LAB / "etf_summary.json").read_text(encoding="utf-8")):
        v, c = e["val"], e["val"]["cert"]
        rows.append({"kind": "etf", "name": e["idea"], "title": e["idea"], "family": "etf", "verdict": c["verdict"], "arl": c["arl"], "depth": c["arl_depth"],
                     "net_sharpe": v["net_sharpe"], "sharpe_x2": v["cost_x2_sharpe"], "dsr": c["deflated_sharpe"], "n_trials": e["n_trials"], "alpha_t": v["alpha_t_spy"],
                     "beta_share": None, "period": f"validation {v['first']} to 2020", "date": "2026-11", "certificate_id": c["certificate_id"]})
    return rows


def mapping() -> dict[str, dict]:
    """catalog id -> map entry."""
    return {k: v for k, v in json.loads((ROOT / "lab_map.json").read_text(encoding="utf-8")).items() if not k.startswith("_")}


def verified_by_catalog() -> dict[str, dict]:
    """catalog id -> result row, for the mapped strategies."""
    by = {(r["kind"], r["name"]): r for r in lab_rows()}
    return {cid: {**by[(m["kind"], m["name"])], "instance": m["instance"]} for cid, m in mapping().items()}


def index_cells(strat_id: str, found: dict[str, dict]) -> tuple[str, str]:
    """(ARL/depth, net Sharpe) cells for the INDEX table."""
    r = found.get(strat_id)
    return (f"{r['arl']}/{r['depth']}", _f(r["net_sharpe"])) if r else (NOT_VERIFIED, "-")


def results_md(strats: list[dict]) -> str:
    """The full results table: every catalog strategy, verified ones with metrics."""
    found = verified_by_catalog()
    out = ["# Catalog results", "", "> Not investment advice. Research and education only. Every verified row is " + NOTE + ".", "",
           "Generated by `build_catalog.py` from `strategy_lab/results/summary.json` and `etf_summary.json` through `lab_map.json`; do not edit by hand. "
           f"{len(found)} of {len(strats)} strategies are verified so far; the rest are *{NOT_VERIFIED}*. A verified row is one instance of the rule (the instrument is named), not the whole strategy family.", "",
           "| id | instance | verdict | ARL / depth | net Sharpe | Sharpe at 2x costs | Deflated Sharpe | n_trials | period | date | note |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in strats:
        r = found.get(s["id"])
        if r:
            out.append(f"| [{s['id']}](cards/{s['id']}.md) | {r['instance']} | {r['verdict']} | ARL {r['arl']}, depth {r['depth']}/4 | {_f(r['net_sharpe'], 3)} | {_f(r['sharpe_x2'], 3)} | {_f(r['dsr'], 3)} | {r['n_trials']} | {r['period']} | {r['date']} | {NOTE} |")
        else:
            out.append(f"| [{s['id']}](cards/{s['id']}.md) | - | {NOT_VERIFIED} | - | - | - | - | - | - | - | - |")
    return "\n".join(out) + "\n"


def reasons(r: dict) -> list[str]:
    """Plain reasons a result did not work, computed from its numbers."""
    out = []
    ns, x2, dsr, at = r["net_sharpe"], r["sharpe_x2"], r["dsr"], r["alpha_t"]
    if ns is not None and ns <= 0:
        out.append(f"net Sharpe {ns:.2f} on validation: it loses money after costs")
    if x2 is not None and ns is not None and ns > 0 and x2 <= 0:
        out.append("the profit disappears at doubled costs")
    if dsr is not None and dsr < 0.95:
        out.append(f"Deflated Sharpe {dsr:.3f} with {r['n_trials']} trials: not separable from luck")
    if at is not None and at < 2:
        out.append(f"alpha t-statistic {at:.2f} against the market, below 2")
    if r.get("beta_share") is not None and r["beta_share"] >= 0.3:
        out.append(f"{r['beta_share']:.0%} of the return is market beta")
    if r["arl"] < 4:
        out.append(f"ARL {r['arl']}: evidence stops early")
    return out or ["no single reason is stored; see the report"]


def failures_md() -> str:
    """'What did not work': every REJECT, and every result whose Deflated Sharpe stays below 0.05."""
    rows = lab_rows()
    rejected = [r for r in rows if r["verdict"] == "REJECT"]
    weak = [r for r in rows if r["verdict"] != "REJECT" and r["dsr"] is not None and r["dsr"] < 0.05]
    out = ["# What did not work", "", "> Not investment advice. Published to save other researchers time: what was tried and why it failed. Every row is " + NOTE + ".", "",
           "Generated by `build_catalog.py` from the Strategy Lab results; reasons are computed from stored numbers, not written by hand. "
           "A failure here is a statement about this rule, this instrument and this sample, not about the whole idea.", "",
           f"## Rejected ({len(rejected)})", "", "| result | family | verdict | ARL / depth | net Sharpe | n_trials | why |", "|---|---|---|---|---|---|---|"]
    out += [f"| {r['name']} | {r['family']} | {r['verdict']} | {r['arl']}/{r['depth']} | {_f(r['net_sharpe'], 3)} | {r['n_trials']} | {'; '.join(reasons(r))} |" for r in rejected]
    out += ["", f"## Not rejected, but no evidence of an edge ({len(weak)})", "", "Deflated Sharpe below 0.05: after paying for the search, indistinguishable from luck.", "",
            "| result | family | verdict | ARL / depth | net Sharpe | Deflated Sharpe | n_trials |", "|---|---|---|---|---|---|---|"]
    out += [f"| {r['name']} | {r['family']} | {r['verdict']} | {r['arl']}/{r['depth']} | {_f(r['net_sharpe'], 3)} | {_f(r['dsr'], 3)} | {r['n_trials']} |" for r in weak]
    return "\n".join(out) + "\n"
