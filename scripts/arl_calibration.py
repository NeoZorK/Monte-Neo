"""Calibrate the ARL rules on the alpha Trap Suite: levels and depth of every trap and honest twin, and false promotions.

For every generator in ``tests/zoo/alpha_cases.py`` it runs ``--seeds`` seeds of the trap and of the twin through
``validate_alpha`` and writes ``docs/guides/arl-calibration.md``: the median ARL and depth of each, how often the trap
reaches a level at least as high as the twin's median (a *false promotion*), and how often a level that is not reached
shows depth above 0 (must be never).
The thresholds of ``arl-rules/1`` stay ``provisional`` until the owner freezes them; this is the evidence for that decision.
Usage: python scripts/arl_calibration.py [--seeds 5] [--jobs 1] [--out PATH]
"""

from __future__ import annotations

import argparse
import statistics
import sys
import warnings
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests" / "zoo"))
sys.path.insert(0, str(ROOT / "src"))

import alpha_cases as ac  # noqa: E402

from monte_neo.arl_rules import load_rules  # noqa: E402

HEADER = "<!-- Generated by scripts/arl_calibration.py — do not edit -->"


def run_one(job: tuple[str, bool, int]) -> dict[str, Any]:
    """One generator, trap or twin, one seed: the ARL, its depth and whether an unreached level shows depth."""
    key, trap, seed = job
    warnings.simplefilter("ignore")
    case = ac.GENERATORS[key](seed, trap)
    r = ac.run_case(case, seed=seed)["readiness"]
    leaks = sum(1 for lv in r["levels"] if not lv["counts"] and lv["depth"] > 0)
    return {"key": key, "trap": trap, "seed": seed, "name": case.name, "arl": r["level"], "depth": r["depth"], "leaks": leaks}


def build(results: list[dict[str, Any]], seeds: int) -> str:
    """The markdown page."""
    rules = load_rules()
    by: dict[tuple[str, bool], list[dict[str, Any]]] = {}
    for r in results:
        by.setdefault((r["key"], r["trap"]), []).append(r)
    rows, promoted, total, leaks = [], 0, 0, sum(r["leaks"] for r in results)
    for key in ac.GENERATORS:
        trap, twin = by[(key, True)], by[(key, False)]
        twin_med = statistics.median(x["arl"] for x in twin)
        fp = sum(1 for x in trap if x["arl"] >= twin_med and twin_med > 0)
        promoted, total = promoted + fp, total + len(trap)
        rows.append(f"| {trap[0]['name']} | {statistics.median(x['arl'] for x in trap):g} | {statistics.median(x['depth'] for x in trap):g}/4 | "
                    f"{twin[0]['name']} | {twin_med:g} | {statistics.median(x['depth'] for x in twin):g}/4 | {fp}/{len(trap)} |")
    return "\n".join([
        HEADER, "", "# ARL calibration on the Trap Suite", "",
        f"Rules `{rules['version']}` ({rules['status']}). {seeds} seed(s) per trap and twin, generators of `tests/zoo/alpha_cases.py`, "
        "`validate_alpha` with 60 placebos.", "",
        "| Trap | ARL | Depth | Honest twin | ARL | Depth | Trap at or above the twin's median ARL |", "|---|---|---|---|---|---|---|", *rows, "",
        f"Trap runs that reached the twin's median level: {promoted} of {total}. Unreached levels that showed depth above 0: {leaks} (must be 0).", "",
        "Reading: a trap that the checks are meant to catch should sit below its twin. Depth criteria that need evidence the alpha path "
        "does not produce (a sealed holdout, live fills) are *not assessed* here and score 0 by rule, so depths in this table are low "
        "by design. Some traps are caught by a check that sits inside an alternative of a level (for example `universe_subsampling` at "
        "level 7) and so do not lower the ARL by themselves; the table reports that instead of hiding it. "
        "The thresholds stay provisional until the owner freezes them.", "",
    ])


def main() -> int:
    """Run the calibration and write the page."""
    p = argparse.ArgumentParser()
    p.add_argument("--seeds", type=int, default=5)
    p.add_argument("--jobs", type=int, default=1)
    p.add_argument("--out", default=str(ROOT / "docs" / "guides" / "arl-calibration.md"))
    a = p.parse_args()
    jobs = [(k, trap, s) for k in ac.GENERATORS for trap in (True, False) for s in range(a.seeds)]
    if a.jobs > 1:
        from concurrent.futures import ProcessPoolExecutor

        with ProcessPoolExecutor(max_workers=a.jobs) as pool:
            results = list(pool.map(run_one, jobs, chunksize=4))
    else:
        results = [run_one(j) for j in jobs]
    Path(a.out).write_text(build(results, a.seeds), encoding="utf-8")
    print(f"wrote {a.out} ({len(results)} runs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
