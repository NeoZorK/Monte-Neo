"""Calibrate the alpha checks: false-alarm rate on honest twins and power on traps, from the A15 zoo generators.

For every check that has a trap and an honest twin (``tests/zoo/alpha_cases.py``) it runs ``--seeds`` seeds of each and writes
a markdown table with Wilson 95 % intervals to ``docs/guides/alpha-calibration.md``.
Usage: python scripts/alpha_calibration.py [--seeds 50] [--jobs 4] [--out PATH]
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
import sys
import warnings
from collections import defaultdict
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests" / "zoo"))

import alpha_cases as ac  # noqa: E402

POWER_TARGET = 0.90
FALSE_ALARM_TARGET = 0.05
HEADER = "<!-- Generated by scripts/alpha_calibration.py — do not edit -->"


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """Wilson score interval for ``k`` successes in ``n`` trials."""
    if n == 0:
        return 0.0, 1.0
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    r = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return max(0.0, (c - r) / d), min(1.0, (c + r) / d)


def run_one(job: tuple[str, bool, int]) -> dict[str, Any]:
    """One generator, trap or twin, one seed: which expectations held and the readiness level reached."""
    key, trap, seed = job
    warnings.simplefilter("ignore")
    case = ac.GENERATORS[key](seed, trap)
    report = ac.run_case(case, seed=seed)
    return {"key": key, "trap": trap, "seed": seed, "name": case.name, "met": ac.met(case, report), "arl": report["readiness"]["level"],
            "status": {e.check: ac.statuses(report).get(e.check) for e in case.expect}}


def cell(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {k / n:.0%} ({lo:.0%}–{hi:.0%})"


def build(results: list[dict[str, Any]], seeds: int) -> str:
    """The markdown page from the raw runs."""
    names: dict[tuple[str, bool], str] = {}
    hits: dict[tuple[str, bool, str], list[bool]] = defaultdict(list)
    arls: dict[tuple[str, bool], list[int]] = defaultdict(list)
    for r in results:
        names[(r["key"], r["trap"])] = r["name"]
        arls[(r["key"], r["trap"])].append(r["arl"])
        for check_id, ok in r["met"].items():
            hits[(r["key"], r["trap"], check_id)].append(ok)
    rows, misses = [], []
    for key in ac.GENERATORS:
        for check_id in sorted({c for (k, t, c) in hits if k == key and t} & {c for (k, t, c) in hits if k == key and not t}):
            trap, twin = hits[(key, True, check_id)], hits[(key, False, check_id)]
            power, fa = sum(trap) / len(trap), 1.0 - sum(twin) / len(twin)
            ok = power >= POWER_TARGET - 1e-9 and fa <= FALSE_ALARM_TARGET + 1e-9  # tolerance: 1 - 19/20 is 0.05000000000000004
            rows.append(f"| `{check_id}` | {names[(key, True)]} | {cell(sum(trap), len(trap))} | {names[(key, False)]} | "
                        f"{cell(len(twin) - sum(twin), len(twin))} | {'yes' if ok else '**no**'} |")
            if not ok:
                why = []
                if power < POWER_TARGET - 1e-9:
                    why.append(f"power {power:.0%} < {POWER_TARGET:.0%}")
                if fa > FALSE_ALARM_TARGET + 1e-9:
                    why.append(f"false alarms {fa:.0%} > {FALSE_ALARM_TARGET:.0%}")
                misses.append(f"- `{check_id}` ({names[(key, True)]} / {names[(key, False)]}): {'; '.join(why)}")
    arl_rows = [f"| {names[(k, True)]} | {statistics.median(arls[(k, True)]):g} | {names[(k, False)]} | {statistics.median(arls[(k, False)]):g} |"
                for k in ac.GENERATORS]
    out = [
        HEADER, "",
        "# Alpha calibration: false alarms and power", "",
        "Generated by scripts/alpha_calibration.py — do not edit.", "",
        f"Each trap and each honest twin of the A15 zoo (`tests/zoo/alpha_cases.py`) was generated with {seeds} seeds "
        "(40 symbols, 1000 business days unless a case needs more) and run through `validate_alpha` with 60 placebos and an AUM of 1e6. "
        "*Power* is the share of trap runs where the named check gave one of the statuses that count as caught (see the case list in the test file); "
        "a *false alarm* is a twin run where the same check did not give its expected quiet status. Intervals are Wilson 95 %. "
        f"Targets: power at least {POWER_TARGET:.0%}, false alarms at most {FALSE_ALARM_TARGET:.0%} (judged on the point estimate).", "",
        "| Check | Trap | Power | Honest twin | False alarms | Targets met |", "|---|---|---|---|---|---|", *rows, "",
        "## Checks that miss their targets", "", *(misses or ["- none"]), "",
        "## Median Alpha Readiness Level", "",
        "| Trap | ARL | Honest twin | ARL |", "|---|---|---|---|", *arl_rows, "",
        "## How to read this", "",
        "The traps and twins are synthetic and were written by the maintainers; the numbers measure how the checks behave on these generators "
        "at this signal strength, not on real markets. A check with a statistical test (`signal_placebo`, `synthetic_market_null`) "
        "has a false-positive rate set by its own threshold (p above 0.10 fails a score with no edge), so its power on a pure-noise score "
        "cannot exceed about 90 % by design. Twins have a deliberately strong edge; with a weaker edge the checks that look at "
        "concentration (`universe_subsampling`) or at the t-statistic of the residual (`residual_alpha`) warn more often. "
        "With few seeds the intervals are wide: read the interval, not only the point.", "",
    ]
    return "\n".join(out)


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--seeds", type=int, default=50)
    p.add_argument("--jobs", type=int, default=4)
    p.add_argument("--raw", default=None, help="save the raw runs as JSON (or load them if the file exists)")
    p.add_argument("--out", default=str(ROOT / "docs" / "guides" / "alpha-calibration.md"))
    a = p.parse_args()
    jobs = [(k, trap, s) for k in ac.GENERATORS for trap in (True, False) for s in range(a.seeds)]
    raw = Path(a.raw) if a.raw else None
    if raw is not None and raw.exists():
        results = json.loads(raw.read_text(encoding="utf-8"))
    elif a.jobs > 1:
        with ProcessPoolExecutor(max_workers=a.jobs) as pool:
            results = list(pool.map(run_one, jobs, chunksize=4))
    else:
        results = [run_one(j) for j in jobs]
    if raw is not None and not raw.exists():
        raw.write_text(json.dumps(results), encoding="utf-8")
    Path(a.out).write_text(build(results, a.seeds), encoding="utf-8")
    print(f"wrote {a.out} ({len(results)} runs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
