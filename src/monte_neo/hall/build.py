"""Build the Hall of Fame outputs from ``hall_of_fame/``: README table, docs page, badges, archives and history.

:func:`build` returns what each file should contain and never writes; :func:`write` writes it and :func:`stale` lists the files
that differ (``monte-neo hall build --check``).
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from monte_neo.disclaimer import SHORT
from monte_neo.hall.ranking import (
    Item,
    archived,
    classify,
    history_text,
    load_items,
    read_history,
    runs,
    tables,
    update_history,
)
from monte_neo.hall.render import badge_name, badge_svg, embed_snippets, medal_of, plain_table, table
from monte_neo.hall.rules import load_rules, sync_page

README_BLOCK = re.compile(r"(<!-- hall:top10:start -->).*?(<!-- hall:top10:end -->)", re.S)
MONTH = re.compile(r"^\d{4}-(0[1-9]|1[0-2])$")
PAGE_URL = "https://github.com/NeoZorK/Monte-Neo/blob/main/docs/hall-of-fame.md"
GUIDE_URL = "https://github.com/NeoZorK/Monte-Neo/blob/main/docs/guides/hall-of-fame.md"


@dataclass
class Result:
    """Outputs of one build: ``errors`` (a non-empty list means nothing should be written), ``files`` and ``obsolete`` badge files."""

    errors: list[str] = field(default_factory=list)
    files: dict[Path, str] = field(default_factory=dict)
    obsolete: list[Path] = field(default_factory=list)


def _holds(history: list[dict[str, Any]], rules: dict[str, Any], scopes: list[str]) -> dict[tuple[str, str], str]:
    out: dict[tuple[str, str], str] = {}
    for scope in scopes:
        for eid, lst in runs(history, rules, scope, by_rank=True).items():
            cur = [r for r in lst if r["current"]]
            if cur:
                out[(scope, eid)] = f"{cur[0]['start']} – {cur[0]['end']}"
    return out


def _past(history: list[dict[str, Any]], rules: dict[str, Any], scopes: list[str], by_id: dict[str, Item]) -> str:
    lines = []
    for scope in scopes:
        for eid, lst in runs(history, rules, scope, by_rank=True).items():
            for r in lst:
                medal = medal_of(r["key"], rules)
                if medal and not r["current"]:
                    e = by_id.get(eid, {"entry": {"strategy": eid, "author": "?"}})["entry"]
                    lines.append(f"- {medal} in `{scope}`: {e['strategy']} ({e['author']}), {r['start']} – {r['end']}")
    return "\n".join(sorted(lines)) or "_No medal has changed hands yet._"


def _page(rules: dict[str, Any], tabs: dict[str, list[Item]], holds: dict[tuple[str, str], str], parts: dict[str, str]) -> str:
    head = f"""# Hall of Fame

> {SHORT}

The Hall of Fame ranks strategies by the **evidence** in their Monte-Neo certificate (ARL, depth, Deflated Sharpe after paying for
`n_trials`), never by return. The strategy itself is not shown. Rules `{rules['version']}` ({rules['status']}) with ARL rules
`{rules['arl_rules_version']}` (provisional): the order can change when the rules are calibrated, and then a new table starts and this one is archived.
How to join: [the guide]({GUIDE_URL}). This page is generated by `monte-neo hall build`; do not edit it by hand.

## Top {rules['top_n']} overall

{table(tabs['overall'], rules, 'overall', holds)}
"""
    cats = "".join(f"\n### {c}\n\n{table(tabs[c], rules, c, holds)}\n" for c in rules["categories"])
    return (head + "\n## Top 10 by category\n" + cats + f"""
## Medal badges

{parts['embed']}

## Past medals

{parts['past']}

## Self-reported (tier C, not ranked)

{parts['self']}

## Not ranked (duplicates, limits, REJECT)

{parts['excluded']}

## Archived tables

{parts['archive']}
""")


def _apply_display(items: list[Item], path: Path) -> None:
    """Show another author text for the entries listed in ``display.json`` (tables and badges only).

    The signed entry keeps its author; this unsigned file only changes what the public pages show, for example
    ``{"hide_author": ["<entry id>"], "shown_as": "Strategy Lab example"}``.
    """
    if not path.exists():
        return
    cfg = json.loads(path.read_text(encoding="utf-8"))
    hidden, shown = set(cfg.get("hide_author", [])), str(cfg.get("shown_as", "not shown"))
    for it in items:
        if it["entry"].get("id") in hidden:
            it["entry"] = {**it["entry"], "author": shown}


def build(root: Path, readme: Path, docs: Path, month: str) -> Result:
    """Everything ``monte-neo hall build`` writes, computed in memory.

    Raises:
        ValueError: ``month`` is not ``YYYY-MM``.
    """
    if not MONTH.match(month):
        raise ValueError("month must be YYYY-MM")
    rules, res = load_rules(), Result()
    items = load_items(root, rules)
    cls = classify(items, rules)
    res.errors = [f"{i['entry'].get('id', '?')}: {e}" for i in cls["errors"] for e in i["errors"]]
    tabs = tables(cls["ranked"], rules)
    _apply_display(items, root / "display.json")  # after ranking: the per-author cap uses the signed author
    history = update_history(read_history(root / "history.jsonl"), month, rules, tabs)
    scopes = list(tabs)
    holds = _holds(history, rules, scopes)
    winners = [(it, sc, m) for sc in scopes for n, it in enumerate(tabs[sc], 1) if (m := medal_of(n, rules))]
    badges = {badge_name(it, sc, m): badge_svg(it, tabs[sc].index(it) + 1, sc, m, holds[(sc, it["entry"]["id"])]) for it, sc, m in winners}
    old = archived(cls["ranked"], rules)
    arch_files = {root / "archive" / f"{h}__{a}.md".replace("/", "-"): _archive(h, a, rows, rules) for (h, a), rows in old.items()}
    parts = {
        "embed": embed_snippets(winners), "past": _past(history, rules, scopes, {i["entry"]["id"]: i for i in items}),
        "self": plain_table(cls["self_reported"], rules),
        "excluded": "\n".join(f"- `{i['entry']['id']}`: {why}" for i, why in cls["excluded"]) or "_None._",
        "archive": "\n".join(f"- `archive/{p.name}`" for p in arch_files) or "_None yet._",
    }
    block = (f"{SHORT}\n\n{table(tabs['overall'], rules, 'overall', holds)}\n\nRanked by evidence (ARL, depth, Deflated Sharpe), not by return; "
             f"rules `{rules['version']}`, provisional. [All categories, medals and how to join]({PAGE_URL}).")
    text = readme.read_text(encoding="utf-8")
    if not README_BLOCK.search(text):
        res.errors.append("README lacks the <!-- hall:top10:start --> / <!-- hall:top10:end --> markers")
    else:
        res.files[readme] = README_BLOCK.sub(lambda m: f"{m.group(1)}\n{block}\n{m.group(2)}", text)
    res.files[docs] = _page(rules, tabs, holds, parts)
    res.files[root / "history.jsonl"] = history_text(history)
    res.files.update(arch_files)
    res.files.update({root / "badges" / n: svg for n, svg in badges.items()})
    res.obsolete = [p for p in (root / "badges").glob("*.svg") if p.name not in badges]
    return res


def _archive(hall: str, arl: str, rows: list[Item], rules: dict[str, Any]) -> str:
    return (f"# Archived Hall of Fame table: {hall} with ARL rules {arl}\n\n> {SHORT}\n\nThis table was ranked under older rules and is kept as it was. "
            f"It is not comparable with the current table (`{rules['version']}`, `{rules['arl_rules_version']}`) and has no medals.\n\n{plain_table(rows, rules)}\n")


def stale(result: Result) -> list[Path]:
    """Files whose content differs from what the build produces (and badge files that should not exist)."""
    diff = [p for p, text in result.files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    return diff + result.obsolete


def write(result: Result) -> list[Path]:
    """Write the outputs and delete obsolete badges; returns the paths that changed."""
    changed = stale(result)
    for p, text in result.files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    for p in result.obsolete:
        p.unlink()
    return changed


def sync_guide(path: Path) -> bool:
    """Regenerate the rule blocks of the guide in place; True when the page changed."""
    old = path.read_text(encoding="utf-8")
    new = sync_page(old)
    path.write_text(new, encoding="utf-8")
    return new != old


__all__ = ["Result", "build", "stale", "sync_guide", "write"]
